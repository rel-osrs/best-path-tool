package com.bestpath.dev;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.Paths;
import java.util.ArrayList;
import java.util.HashMap;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Map;
import java.util.Set;
import java.util.regex.Matcher;
import java.util.regex.Pattern;
import net.runelite.api.Quest;
import net.runelite.api.gameval.VarbitID;

/**
 * DEV ONLY (src/test, never in the plugin jar): writes the plugin's
 * {@code quest-vars.tsv}, the varbit / varp that holds each quest's progress,
 * from Quest Helper's data (its quest varbit / varp numbers are used as data,
 * with permission, and "Quest Helper &lt;file&gt;" is each record's source; its code is not used).
 *
 * <p>Reads {@code QuestHelperQuest.java} (which RuneLite {@link Quest} an
 * entry is, and its {@code QuestVarbits} / {@code QuestVarPlayer} entry),
 * {@code QuestVarbits.java} (a RuneLite gameval {@code VarbitID} name per
 * entry) and {@code QuestVarPlayer.java} (a varp number per entry). The
 * VarbitID names become numbers through RuneLite's public gameval constants.
 * A quest with several entries (Recipe for Disaster's sub-quests, both Shield
 * of Arrav gangs) gets every var.
 *
 * <p>{@code gradlew questVarsExtract -PquestHelper=<reference/quest-helper folder>}
 */
public final class QuestVarsExtract
{
	private static final String OUT = "src/main/resources/com/bestpath/player/quest-vars.tsv";
	private static final Pattern QUEST_LINE = Pattern.compile(
		"^\\s*([A-Z0-9_]+)\\(.*?\\bQuest\\.([A-Z0-9_]+)\\b.*?\\b(QuestVarbits|QuestVarPlayer)\\.([A-Z0-9_]+)\\b");
	private static final Pattern VARBIT_ENTRY = Pattern.compile("^\\s*([A-Z0-9_]+)\\(VarbitID\\.([A-Za-z0-9_]+)\\)");
	private static final Pattern VARP_ENTRY = Pattern.compile("^\\s*([A-Z0-9_]+)\\((\\d+)\\)");

	private QuestVarsExtract()
	{
	}

	public static void main(String[] args) throws Exception
	{
		Path qh = Paths.get(args.length > 0 ? args[0] : "reference/quest-helper");
		Path info = qh.resolve("src/main/java/com/questhelper/questinfo");
		String commit = args.length > 1 ? args[1] : "";
		Map<String, String> varbitNames = entries(info.resolve("QuestVarbits.java"), VARBIT_ENTRY);
		Map<String, String> varps = entries(info.resolve("QuestVarPlayer.java"), VARP_ENTRY);

		List<String> out = new ArrayList<>();
		out.add("# The varbit / varp that holds each quest's progress, for the plugin's quest re-reads (a quest's state is");
		out.add("# read again only when one of its vars changes). Generated by gradlew questVarsExtract (src/test/java/com/");
		out.add("# bestpath/dev/QuestVarsExtract.java) from Quest Helper's data" + (commit.isEmpty() ? "" : " (commit " + commit + ")")
			+ ", BSD-2-Clause, used as data with");
		out.add("# permission (its code is not used); VarbitID names turned into numbers with RuneLite's gameval.");
		out.add("# Quest Helper: Copyright (c) 2020, Zoinkwiz. All rights reserved. BSD 2-Clause License.");
		out.add("#quest (RuneLite Quest name)\tkind\tid\tsource");
		Set<String> seen = new LinkedHashSet<>();
		int quests = 0;
		Set<String> questNames = new LinkedHashSet<>();
		for (String line : Files.readAllLines(info.resolve("QuestHelperQuest.java"), StandardCharsets.UTF_8))
		{
			Matcher m = QUEST_LINE.matcher(line);
			if (!m.find())
			{
				continue;
			}
			String entry = m.group(1);
			String quest = m.group(2);
			Quest.valueOf(quest); // must be RuneLite's
			String kind;
			int id;
			String source;
			if (m.group(3).equals("QuestVarbits"))
			{
				String gameval = varbitNames.get(m.group(4));
				if (gameval == null)
				{
					throw new IllegalStateException("QuestVarbits." + m.group(4) + " not found");
				}
				kind = "varbit";
				id = VarbitID.class.getField(gameval).getInt(null);
				source = "Quest Helper QuestHelperQuest.java " + entry + ", QuestVarbits.java " + m.group(4)
					+ " (VarbitID." + gameval + ")";
			}
			else
			{
				String n = varps.get(m.group(4));
				if (n == null)
				{
					throw new IllegalStateException("QuestVarPlayer." + m.group(4) + " not found");
				}
				kind = "varp";
				id = Integer.parseInt(n);
				source = "Quest Helper QuestHelperQuest.java " + entry + ", QuestVarPlayer.java " + m.group(4);
			}
			if (seen.add(quest + "\t" + kind + "\t" + id))
			{
				out.add(quest + "\t" + kind + "\t" + id + "\t" + source);
				if (questNames.add(quest))
				{
					quests++;
				}
			}
		}
		Path target = Paths.get(OUT);
		Files.createDirectories(target.getParent());
		Files.write(target, out, StandardCharsets.UTF_8);
		System.out.println("Wrote " + (out.size() - 6) + " vars for " + quests + " quests to " + target.toAbsolutePath()
			+ " (RuneLite knows " + Quest.values().length + " quests)");
	}

	private static Map<String, String> entries(Path file, Pattern p) throws IOException
	{
		Map<String, String> m = new HashMap<>();
		for (String line : Files.readAllLines(file, StandardCharsets.UTF_8))
		{
			Matcher x = p.matcher(line);
			if (x.find())
			{
				m.put(x.group(1), x.group(2));
			}
		}
		return m;
	}
}
