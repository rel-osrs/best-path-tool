package com.bestpath.tool.clue;

import com.bestpath.tool.cache.CacheInfo;
import com.bestpath.tool.cache.LoadedCache;
import java.io.File;
import java.util.ArrayList;
import java.util.HashMap;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.TreeMap;
import net.runelite.cache.ConfigType;
import net.runelite.cache.DBRowManager;
import net.runelite.cache.IndexType;
import net.runelite.cache.ItemManager;
import net.runelite.cache.NpcManager;
import net.runelite.cache.ObjectManager;
import net.runelite.cache.definitions.DBRowDefinition;
import net.runelite.cache.definitions.EnumDefinition;
import net.runelite.cache.definitions.ItemDefinition;
import net.runelite.cache.definitions.NpcDefinition;
import net.runelite.cache.definitions.ObjectDefinition;
import net.runelite.cache.definitions.VarbitDefinition;
import net.runelite.cache.definitions.loaders.EnumLoader;
import net.runelite.cache.definitions.loaders.VarbitLoader;
import net.runelite.cache.fs.Archive;
import net.runelite.cache.fs.ArchiveFiles;
import net.runelite.cache.fs.FSFile;
import net.runelite.cache.fs.Index;
import net.runelite.cache.fs.Storage;
import net.runelite.cache.fs.Store;

/**
 * Developer aid: regenerates {@code data/clues/clue-steps.tsv} from the game
 * cache's clue-helper tables ({@link ClueExtractor}). Nothing here is typed
 * by hand; run it again after a cache update and compare with git.
 * {@code gradlew -p tool clueExtract --args="<cacheDir> [outFile]"}
 */
public final class ClueExtractCli
{
	private ClueExtractCli()
	{
	}

	public static void main(String[] args) throws Exception
	{
		File folder = LoadedCache.findCacheFolder(new File(args[0]));
		if (folder == null)
		{
			throw new IllegalArgumentException("no cache (main_file_cache.dat2) in " + args[0]);
		}
		File out = new File(args.length > 1 ? args[1] : "data/clues/clue-steps.tsv");
		CacheInfo info = CacheInfo.find(folder);
		String cacheName = info == null ? "cache ?" : "cache " + info.getOpenrs2Id();
		List<ClueStep> steps;
		try (Store store = new Store(folder))
		{
			store.load();
			steps = new ClueExtractor(new StoreSource(store), cacheName).extract();
		}
		List<String> header = new ArrayList<>();
		header.add("BestPath clue steps: GENERATED by `gradlew -p tool clueExtract` from the game cache's clue-helper tables; do not edit by hand.");
		header.add("Source: " + cacheName + (info == null ? "" : " (build " + info.getBuild() + ")")
			+ ". Table and column names: RuneLite gameval DBTableID.Cluehelper*. Format: data/clues/README.md.");
		header.add(steps.size() + " steps.");
		ClueFile.write(out, steps, header);
		int withTile = 0;
		int flagged = 0;
		for (ClueStep s : steps)
		{
			withTile += s.hasTile() ? 1 : 0;
			flagged += s.checks.isEmpty() ? 0 : 1;
		}
		System.out.printf(Locale.ROOT, "%d clue steps (%d with a target tile, %d with checks) -> %s%n", steps.size(), withTile, flagged, out);
		System.out.print(ClueExtractor.summary(steps));
	}

	/** The real cache. */
	static final class StoreSource implements ClueExtractor.Source
	{
		private final Map<Integer, Map<Integer, Object[][]>> byTable = new HashMap<>();
		private final Map<Integer, Object[][]> byId = new HashMap<>();
		private final Map<Integer, List<Integer>> itemsByRow = new TreeMap<>();
		private final Map<Integer, String> npcs = new HashMap<>();
		private final Map<Integer, String> objects = new HashMap<>();
		private final Map<Integer, String> items = new HashMap<>();
		private final Map<Integer, Integer> objectVarbits = new HashMap<>();
		/** Item param id -> param value -> item ids (int params only). */
		private final Map<Integer, Map<Integer, List<Integer>>> itemParams = new HashMap<>();
		private final Map<Integer, int[]> varbits = new HashMap<>();
		private final Map<Integer, byte[]> enums;

		StoreSource(Store store) throws java.io.IOException
		{
			enums = configFiles(store, ConfigType.ENUM);
			VarbitLoader vl = new VarbitLoader();
			for (Map.Entry<Integer, byte[]> e : configFiles(store, ConfigType.VARBIT).entrySet())
			{
				VarbitDefinition v = vl.load(e.getKey(), e.getValue());
				varbits.put(e.getKey(), new int[]{v.getIndex(), v.getLeastSignificantBit(), v.getMostSignificantBit()});
			}
			DBRowManager rows = new DBRowManager(store);
			rows.load();
			for (DBRowDefinition r : rows.getRows())
			{
				if (r.getColumnValues() != null)
				{
					byId.put(r.getId(), r.getColumnValues());
					byTable.computeIfAbsent(r.getTableId(), k -> new TreeMap<>()).put(r.getId(), r.getColumnValues());
				}
			}
			NpcManager nm = new NpcManager(store);
			nm.load();
			Map<Integer, NpcDefinition> npcDefs = new HashMap<>();
			for (NpcDefinition n : nm.getNpcs())
			{
				npcDefs.put(n.getId(), n);
			}
			for (NpcDefinition n : npcDefs.values())
			{
				npcs.put(n.getId(), npcName(n, npcDefs));
			}
			ObjectManager om = new ObjectManager(store);
			om.load();
			Map<Integer, ObjectDefinition> defs = new HashMap<>();
			for (ObjectDefinition o : om.getObjects())
			{
				defs.put(o.getId(), o);
			}
			for (ObjectDefinition o : defs.values())
			{
				objects.put(o.getId(), objectName(o, defs));
				objectVarbits.put(o.getId(), o.getVarbitID());
			}
			ItemManager im = new ItemManager(store);
			im.load();
			List<ItemDefinition> sorted = new ArrayList<>(im.getItems());
			sorted.sort(java.util.Comparator.comparingInt(ItemDefinition::getId));
			for (ItemDefinition d : sorted)
			{
				items.put(d.getId(), d.getName());
				Object row = d.getParams() == null ? null : d.getParams().get(ClueExtractor.PARAM_CLUE_ROW);
				if (row instanceof Number)
				{
					itemsByRow.computeIfAbsent(((Number) row).intValue(), k -> new ArrayList<>()).add(d.getId());
				}
				Object group = d.getParams() == null ? null : d.getParams().get(ClueExtractor.PARAM_TRAIL_GROUP);
				if (group instanceof Number)
				{
					itemParams.computeIfAbsent(ClueExtractor.PARAM_TRAIL_GROUP, k -> new TreeMap<>())
						.computeIfAbsent(((Number) group).intValue(), k -> new ArrayList<>()).add(d.getId());
				}
			}
		}

		/** The files of one config archive (enums, varbits), by file id. */
		private static Map<Integer, byte[]> configFiles(Store store, ConfigType type) throws java.io.IOException
		{
			Storage storage = store.getStorage();
			Index index = store.getIndex(IndexType.CONFIGS);
			Archive archive = index.getArchive(type.getId());
			ArchiveFiles files = archive.getFiles(storage.loadArchive(archive));
			Map<Integer, byte[]> out = new HashMap<>();
			for (FSFile f : files.getFiles())
			{
				out.put(f.getFileId(), f.getContents());
			}
			return out;
		}

		private EnumDefinition enumDef(int id)
		{
			byte[] b = enums.get(id);
			return b == null ? null : new EnumLoader().load(id, b);
		}

		@Override
		public Map<Integer, List<Integer>> itemsByParam(int param)
		{
			return itemParams.getOrDefault(param, Map.of());
		}

		@Override
		public int objectVarbit(int objectId)
		{
			return objectVarbits.getOrDefault(objectId, -1);
		}

		@Override
		public int[] varbit(int id)
		{
			int[] v = varbits.get(id);
			return v == null ? null : v.clone();
		}

		@Override
		public Map<Integer, Integer> enumInts(int id)
		{
			EnumDefinition d = enumDef(id);
			Map<Integer, Integer> out = new HashMap<>();
			if (d != null && d.getKeys() != null && d.getIntVals() != null)
			{
				for (int i = 0; i < d.getKeys().length; i++)
				{
					out.put(d.getKeys()[i], d.getIntVals()[i]);
				}
			}
			return out;
		}

		@Override
		public Map<Integer, String> enumStrings(int id)
		{
			EnumDefinition d = enumDef(id);
			Map<Integer, String> out = new HashMap<>();
			if (d != null && d.getKeys() != null && d.getStringVals() != null)
			{
				for (int i = 0; i < d.getKeys().length; i++)
				{
					out.put(d.getKeys()[i], d.getStringVals()[i]);
				}
			}
			return out;
		}

		/** The object's name; a nameless object that changes with a varbit takes its first named form's name. */
		private static String objectName(ObjectDefinition o, Map<Integer, ObjectDefinition> defs)
		{
			String n = o.getName();
			if ((n == null || n.equals("null")) && o.getConfigChangeDest() != null)
			{
				for (int c : o.getConfigChangeDest())
				{
					ObjectDefinition d = defs.get(c);
					if (d != null && d.getName() != null && !d.getName().equals("null"))
					{
						return d.getName();
					}
				}
			}
			return n;
		}

		/** The NPC's name; a nameless NPC that changes with a varbit takes its first named form's name. */
		private static String npcName(NpcDefinition n, Map<Integer, NpcDefinition> defs)
		{
			String name = n.getName();
			if ((name == null || name.equals("null")) && n.getConfigs() != null)
			{
				for (int c : n.getConfigs())
				{
					NpcDefinition d = defs.get(c);
					if (d != null && d.getName() != null && !d.getName().equals("null"))
					{
						return d.getName();
					}
				}
			}
			return name;
		}

		@Override
		public Map<Integer, Object[][]> rows(int table)
		{
			return byTable.getOrDefault(table, new TreeMap<>());
		}

		@Override
		public Object[][] row(int rowId)
		{
			return byId.get(rowId);
		}

		@Override
		public Map<Integer, List<Integer>> itemsByRow()
		{
			return itemsByRow;
		}

		@Override
		public String npcName(int id)
		{
			return npcs.get(id);
		}

		@Override
		public String objectName(int id)
		{
			return objects.get(id);
		}

		@Override
		public String itemName(int id)
		{
			return items.get(id);
		}
	}
}
