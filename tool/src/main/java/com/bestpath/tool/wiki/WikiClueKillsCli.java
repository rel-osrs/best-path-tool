/**
 * DEVELOPMENT-TIME ONLY (project rule 1: Wiki data is gathered only at development time): where the NPCs of the
 * "kill" clue steps can be found. The cache's clue tables name the NPCs but
 * give no tile, and NPC spawns are not in the cache, so the tiles come from
 * the {@code {{LocLine}}} templates on each NPC's Wiki page. Never used by
 * the plugin at run time.
 *
 * <p>Polite: the MediaWiki API only, a descriptive User-Agent, at least 3 s
 * between requests, 50 pages per request, every response kept in
 * {@code <wikiCache>/clues/}. Real requests count against the shared daily
 * budget in {@code <wikiCache>/review/_state.json} (the region-review
 * wiki.py budget, 1000 a day), when that file exists.
 *
 * <p>Output: {@code data/wiki/clue-kill-spawns.tsv} (CC BY-NC-SA 3.0, page
 * and revision per line). {@code gradlew -p tool wikiClueKills --args="[wikiCache] [refresh]"}
 */
public final class WikiClueKillsCli
{
	private static final String API = "https://oldschool.runescape.wiki/api.php";
	private static final String USER_AGENT = "BestPathDataTool-dev/0.1 (development-time data check for a RuneLite route-finding plugin; "
		+ "NPC locations for clue steps only, results cached locally)";
	private static final long PAUSE_MS = 3000;
	private static final int BUDGET = 1000;

	private final HttpClient http = HttpClient.newBuilder().connectTimeout(Duration.ofSeconds(20)).build();
	private final File wikiCache;
	private final boolean refresh;
	private int requests;

	private WikiClueKillsCli(File wikiCache, boolean refresh)
	{
		this.wikiCache = wikiCache;
		this.refresh = refresh;
	}

	/** One place an NPC is found, from one LocLine. */
	static final class Spawn
	{
		final String location;
		final int x;
		final int y;
		final int plane;
		/** The Wiki map layer ("mapID"): -1/0 the surface, other numbers a dungeon or quest layer (same game tiles). */
		final String mapId;

		Spawn(String location, int x, int y, int plane, String mapId)
		{
			this.location = location;
			this.mapId = mapId;
			this.x = x;
			this.y = y;
			this.plane = plane;
		}
	}

	public static void main(String[] args) throws Exception
	{
		File cache = new File(args.length > 0 ? args[0] : "cache/wiki");
		new WikiClueKillsCli(cache, args.length > 1 && args[1].equals("refresh")).run();
	}

	private void run() throws Exception
	{
		List<ClueStep> steps = ClueFile.read(new File("data/clues/clue-steps.tsv"));
		Map<ClueStep, List<String>> kills = new LinkedHashMap<>();
		Set<String> titles = new LinkedHashSet<>();
		for (ClueStep s : steps)
		{
			if (s.target.equals("kill"))
			{
				List<String> names = new ArrayList<>();
				for (String n : s.targetName.split(" / "))
				{
					if (!n.isBlank() && !n.equals("?"))
					{
						names.add(n.trim());
						titles.add(n.trim());
					}
				}
				kills.put(s, names);
			}
		}
		// title asked -> {page title, revision, wikitext}
		Map<String, String[]> pages = new HashMap<>();
		List<String> list = new ArrayList<>(titles);
		for (int i = 0; i < list.size(); i += 50)
		{
			addPages(list.subList(i, Math.min(list.size(), i + 50)), pages);
		}
		StringBuilder sb = new StringBuilder();
		sb.append("# Where the NPCs of the clue \"kill\" steps are found. DEVELOPMENT-TIME data from the Old School RuneScape Wiki\n");
		sb.append("# ({{LocLine}} templates on each NPC's page), CC BY-NC-SA 3.0 (data/wiki/LICENSE-WIKI.txt); page and revision per line.\n");
		sb.append("# GENERATED by `gradlew -p tool wikiClueKills`; do not edit by hand. Every LocLine is kept; mapID is the Wiki's map layer (a dungeon or quest layer, same game tiles).\n");
		sb.append("step\tnpc\tpage\trevision\tlocation\tmapID\tx\ty\tplane\n");
		int lines = 0;
		for (Map.Entry<ClueStep, List<String>> e : kills.entrySet())
		{
			int before = lines;
			for (String n : e.getValue())
			{
				lines += appendSpawns(sb, e.getKey(), n, pages.get(n));
			}
			System.out.printf(Locale.ROOT, "%s %-60s %d spawn tiles%n", e.getKey().key, e.getKey().targetName, lines - before);
		}
		File out = new File("data/wiki/clue-kill-spawns.tsv");
		out.getParentFile().mkdirs();
		Files.writeString(out.toPath(), sb.toString(), StandardCharsets.UTF_8);
		System.out.printf(Locale.ROOT, "%d lines -> %s; %d web requests%n", lines, out, requests);
	}

	/** Asks for one batch of pages (following redirects) and adds each found one to {@code pages} under the title asked. */
	private void addPages(List<String> batch, Map<String, String[]> pages) throws IOException, InterruptedException
	{
		String url = API + "?action=query&format=json&redirects=1&prop=revisions&rvprop=content%7Cids&rvslots=main&titles="
			+ URLEncoder.encode(String.join("|", batch), StandardCharsets.UTF_8);
		JsonObject q = new JsonParser().parse(get(url, "kills-" + Integer.toHexString(String.join("|", batch).hashCode())))
			.getAsJsonObject().getAsJsonObject("query");
		Map<String, String> moved = new HashMap<>();
		for (String key : new String[]{"normalized", "redirects"})
		{
			if (q.has(key))
			{
				for (JsonElement e : q.getAsJsonArray(key))
				{
					moved.put(e.getAsJsonObject().get("from").getAsString(), e.getAsJsonObject().get("to").getAsString());
				}
			}
		}
		Map<String, String[]> byTitle = new HashMap<>();
		for (Map.Entry<String, JsonElement> pe : q.getAsJsonObject("pages").entrySet())
		{
			JsonObject page = pe.getValue().getAsJsonObject();
			if (page.has("revisions"))
			{
				JsonObject rev = page.getAsJsonArray("revisions").get(0).getAsJsonObject();
				String title = page.get("title").getAsString();
				byTitle.put(title, new String[]{title, rev.get("revid").getAsString(),
					rev.getAsJsonObject("slots").getAsJsonObject("main").get("*").getAsString()});
			}
		}
		for (String t : batch)
		{
			String to = moved.getOrDefault(t, t);
			to = moved.getOrDefault(to, to);
			if (byTitle.containsKey(to))
			{
				pages.put(t, byTitle.get(to));
			}
		}
	}

	/** Adds a line per spawn of NPC {@code n}'s page ({@code p}, null: none, printed); returns how many. */
	private static int appendSpawns(StringBuilder sb, ClueStep step, String n, String[] p)
	{
		if (p == null)
		{
			System.out.printf(Locale.ROOT, "%s: no Wiki page for %s%n", step.key, n);
			return 0;
		}
		int lines = 0;
		for (Spawn s : spawns(p[2]))
		{
			sb.append(step.key).append('\t').append(n).append('\t').append(p[0]).append('\t').append(p[1]).append('\t')
				.append(s.location.isEmpty() ? "-" : s.location).append('\t').append(s.mapId.isEmpty() ? "-" : s.mapId).append('\t').append(s.x).append('\t').append(s.y).append('\t').append(s.plane).append('\n');
			lines++;
		}
		return lines;
	}

	/**
	 * Tiles from the page's {@code {{LocLine ...}}} templates, in both forms the Wiki writes them: "|x:3202,y:3253"
	 * and bare pairs ("|3157,9698|3163,9699"). The same reader as the Slayer places ({@link SlayerPages#spawns}).
	 */
	static List<Spawn> spawns(String text)
	{
		return SlayerPages.spawns(text);
	}

	/** The template's parameters, split at the "|" that are not inside [[links]] or {{templates}}. */
	static List<String> topLevelParts(String body)
	{
		List<String> out = new ArrayList<>();
		int depth = 0;
		int start = 0;
		for (int i = 0; i < body.length(); i++)
		{
			char c = body.charAt(i);
			if ((c == '[' || c == '{') && i + 1 < body.length() && body.charAt(i + 1) == c)
			{
				depth++;
				i++;
			}
			else if ((c == ']' || c == '}') && i + 1 < body.length() && body.charAt(i + 1) == c)
			{
				depth = Math.max(0, depth - 1);
				i++;
			}
			else if (c == '|' && depth == 0)
			{
				out.add(body.substring(start, i));
				start = i + 1;
			}
		}
		out.add(body.substring(start));
		return out;
	}

	/** A LocLine's location as plain text: links become their text, references and templates go. */
	static String plainLocation(String s)
	{
		return s.replaceAll("(?s)<ref[^>]*/>", "").replaceAll("(?s)<ref[^>]*>.*?</ref>", "")
			.replaceAll("\\{\\{FloorNumber\\|(?:uk=)?(\\d+)[^}]*}}", "floor $1").replaceAll("\\{\\{Fairycode\\|([^}]*)}}", "$1")
			.replaceAll("\\{\\{[^}]*}}", "").replaceAll("\\[\\[(?:[^]|]*\\|)?([^]]*)]]", "$1").replaceAll("[\\t\\n]+", " ").trim();
	}

	/** A cached response, or one polite request (saved for next time, counted in the shared budget). */
	private String get(String url, String cacheName) throws IOException, InterruptedException
	{
		File dir = new File(wikiCache, "clues");
		dir.mkdirs();
		File f = new File(dir, cacheName + ".json");
		if (f.isFile() && !refresh)
		{
			return Files.readString(f.toPath(), StandardCharsets.UTF_8);
		}
		File state = new File(wikiCache, "review/_state.json");
		JsonObject s = state.isFile() ? new JsonParser().parse(Files.readString(state.toPath(), StandardCharsets.UTF_8)).getAsJsonObject() : new JsonObject();
		String today = LocalDate.now().toString();
		if (!today.equals(s.has("day") ? s.get("day").getAsString() : ""))
		{
			s.addProperty("day", today);
			s.addProperty("used", 0);
		}
		int used = s.has("used") ? s.get("used").getAsInt() : 0;
		if (used >= BUDGET)
		{
			throw new IOException("the shared wiki budget for today is used up (" + used + " requests)");
		}
		double last = s.has("last") ? s.get("last").getAsDouble() : 0;
		long wait = (long) (last * 1000) + PAUSE_MS - System.currentTimeMillis();
		if (wait > 0)
		{
			Thread.sleep(wait);
		}
		HttpRequest req = HttpRequest.newBuilder(URI.create(url)).header("User-Agent", USER_AGENT)
			.timeout(Duration.ofSeconds(60)).GET().build();
		HttpResponse<String> resp = http.send(req, HttpResponse.BodyHandlers.ofString(StandardCharsets.UTF_8));
		requests++;
		s.addProperty("used", used + 1);
		s.addProperty("last", System.currentTimeMillis() / 1000.0);
		if (state.getParentFile().isDirectory())
		{
			Files.writeString(state.toPath(), s.toString(), StandardCharsets.UTF_8);
		}
		if (resp.statusCode() != 200)
		{
			throw new IOException("HTTP " + resp.statusCode() + " for " + url);
		}
		Files.writeString(f.toPath(), resp.body(), StandardCharsets.UTF_8);
		return resp.body();
	}
}
